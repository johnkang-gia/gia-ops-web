-- 하원 체크표 밖의 노선을 끕니다 — 등원 39개 · 배정 없는 하원 11개.
--
-- ── 기준 ──────────────────────────────────────────────────────────────
--
-- **하원 체크표에 뜨는 명단이 정답입니다.** 행정실이 매일 쓰고 종이로 뽑는 유일한 셔틀
-- 자료이고, 거기 뜨는 배정 109건은 전부 학생 번호가 붙어 있습니다. 다른 셔틀 자료는 이것에
-- 맞춥니다.
--
-- ── 무엇이 밖에 있었나 ──────────────────────────────────────────────────
--
-- · 등원 노선 39개(정규학기)와 그 배정 243건. 231건은 학생 번호 없이 이름만 있습니다.
--   등원은 지금 운영하지 않는데 「쓰는 노선」으로 켜져 있어서, 셔틀 개요·노선·학생·지역
--   화면과 점검 화면에 계속 떴습니다. 점검 화면의 「명부에 안 이어진 배정 231건」이 전부
--   이것이었습니다 - 체크표에는 그런 줄이 하나도 없습니다.
-- · 하원 정규학기인데 배정이 0명인 노선 11개. 노선 목록과 지도에 빈 차로 떴습니다.
--
-- ── 무엇을 하나 ──────────────────────────────────────────────────────
--
-- **끕니다. 지우지 않습니다.** `active = false` 면 모든 화면이 안 읽습니다(쓰는 노선만
-- 읽도록 이미 되어 있습니다). 배정·정류장은 그대로 남아, 등원을 다시 돌릴 때 켜면 됩니다.
--
-- 빈 노선은 번호를 손으로 적지 않고 **지금 상태에서 셉니다** - 적어둔 번호는 이 파일을
-- 돌리는 날 이미 달라져 있을 수 있습니다.

-- 등원 전부
update public.shuttle_routes
   set active = false
 where direction = '등원'
   and active = true;

-- 하원 정규학기 중 배정이 하나도 없는 노선
update public.shuttle_routes r
   set active = false
 where r.direction = '하원'
   and r.term = '정규학기'
   and r.active = true
   and not exists (
     select 1
       from public.shuttle_stops s
       join public.shuttle_assignments a on a.stop_id = s.id
      where s.route_id = r.id
   );

