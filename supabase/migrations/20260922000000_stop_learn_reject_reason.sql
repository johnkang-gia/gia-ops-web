-- 정류장 학습에서 **탈락한 이유**를 관측에 남깁니다.
--
-- ── 무엇이 문제였나 ─────────────────────────────────────────────────────────
--
-- 정류장 656곳 중 좌표가 학습된 곳은 2곳뿐인데, 화면에는 그 2곳의 「10일 관측 · 83%」만
-- 떴습니다. 나머지 654곳은 목록에 아예 나오지 않으니, 학습이 멈춰 있다는 사실 자체가
-- 화면에 나타나지 않았습니다. 관측은 매일 20~35건씩 정상적으로 쌓이고 있었는데도요.
--
-- 실제 탈락 이유는 셋이었습니다.
--   · 노선의 정류장에 좌표가 아예 없음 (355곳)
--   · 관측 일수가 문턱에 미달
--   · 가장 가까운 정류장이 400m 밖
--
-- 셋 다 고칠 수 있는 것인데, 화면이 「학습된 것」만 보여주니 고칠 계기가 없었습니다.
-- 이 칸은 그 이유를 사람이 볼 수 있는 자리에 놓기 위한 것입니다.
--
-- verdict('stop'/'transit')만으로는 부족합니다 - 'transit'은 「신호대기로 판단」과
-- 「붙일 정류장이 없음」을 구별하지 못하는데, 앞은 정상이고 뒤는 고쳐야 하는 문제입니다.

alter table public.shuttle_stop_observations
  add column if not exists reject_reason text;

comment on column public.shuttle_stop_observations.reject_reason is
  '정류장으로 인정되지 않은 이유(사람이 읽는 문장). 인정된 관측은 null 입니다.';

