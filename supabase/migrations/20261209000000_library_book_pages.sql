-- ===== 책 두께(쪽수)와 렉사일 =====
--
-- 요청: "렉사일별(렉사일은 얇은 책(단어 얼마 안 되는 책)부터 두꺼운 책(단어 많은 책) 순으로,
-- 그리고 렉사일은 만약 검색이 불가능하다면 책 정보에서 얻을 수 있다면 어림짐작해서 설정해줘)."
--
-- ── 렉사일은 조회처에서 안 나옵니다 ───────────────────────────────────────
-- 렉사일 지수는 MetaMetrics 의 자료입니다. 우리가 쓰는 네 조회처(국중·카카오·구글북스·
-- 오픈라이브러리)는 어디도 렉사일을 주지 않습니다. 없는 것을 있는 척 지어내면, 그 숫자를 보고
-- 책을 고른 아이에게 거짓말을 하는 셈입니다.
--
-- 대신 **쪽수**는 구글북스(pageCount)와 오픈라이브러리(number_of_pages)가 줍니다. 그리고
-- 선생님이 말씀하신 기준 자체가 "얇은 책(단어 얼마 안 되는 책)부터 두꺼운 책(단어 많은 책)
-- 순"입니다 - 그 줄 세우기에는 쪽수가 바로 맞는 자료입니다. 그래서 쪽수를 받아 적고, 정리
-- 계획은 그 숫자로 얇은 것부터 세웁니다.
--
-- lexile 칸은 비워 둡니다. 나중에 학교에서 쓰는 목록(또는 사람이 직접)으로 채워 넣으면 그때는
-- 그 값이 우선입니다 - 자동으로 지어내지 않습니다.

alter table public.lib_books
  /** 쪽수. 조회처(구글북스·오픈라이브러리)가 준 값. 얇은 책부터 세울 때 씁니다. */
  add column if not exists pages integer,
  /** 렉사일 지수(예: 620). 조회처가 주지 않으므로 사람이 채우는 칸입니다. */
  add column if not exists lexile integer;

comment on column public.lib_books.pages is
  '쪽수(조회처 값). 정리 계획에서 얇은 책 → 두꺼운 책 순으로 세울 때 씁니다. 렉사일을 못 구하므로 그 자리를 대신합니다.';
comment on column public.lib_books.lexile is
  '렉사일 지수. 조회처가 주지 않아 자동으로는 채우지 않습니다 - 지어낸 숫자보다 빈칸이 낫습니다.';

-- 얇은 것부터 줄 세울 때 보는 칸입니다.
create index if not exists lib_books_pages_idx on public.lib_books (label_level, pages);

