/**
 * 구글시트 명부 수신에서 **창구와 화면이 같이 알아야 하는 값**.
 *
 * 「연결 시험」은 진짜 수신과 같은 자리(마지막 수신)에 기록을 남깁니다. 그래야 시각이
 * 찍히는지까지 한 번에 확인됩니다. 대신 화면은 이것이 시험이었다는 것을 알아야 합니다 -
 * 모르면 시험 기록을 진짜 수신으로 읽고 「이름 칸을 못 찾았다」 같은 헛경고를 냅니다.
 *
 * 그래서 표시 글자를 **양쪽에서 같은 상수로** 씁니다. 한쪽에만 적힌 글자는 다른 쪽을
 * 고칠 때 조용히 어긋납니다.
 */
export const TEST_MARK = "(연결 시험)";

export function isTestReceipt(columns: string | null | undefined): boolean {
  return (columns ?? "") === TEST_MARK;
}
