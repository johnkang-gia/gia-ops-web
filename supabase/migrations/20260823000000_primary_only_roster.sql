-- ===== 105. 초등부 명부 확정 - 명부에 없으면 보류, 명부에 없는 반은 삭제 =====
-- 요청: "일단 지금 명단에 없으면 전부 보류하고, 나중에 중등부 명단을 주면 다시 비교해서 지금
-- 명단에 없지만, 이름이 있는 아이들 비교해서, 중고등학생 명단에도 없으면 퇴소처리 해줘.
-- 우선은 반구성도 지금 명단에 없다면 아예 없애줘 일단 초등부는 이명단이 확정이라 다른 반이
-- 있어서는 안돼"
--
-- 이번에 넣은 "26-27 GIA Primary Roster"가 초등부 확정 명부입니다. 그 밖의 것을 어떻게 할지는
-- 두 가지로 나뉩니다.
--
--   학생 → 보류 (지우지 않음)
--     명부에 없다고 바로 퇴소로 찍으면, 사실은 중고등부라서 이 명부에 없었을 뿐인 학생까지
--     퇴소가 됩니다. 그래서 "아직 판단하지 않았다"는 뜻의 보류 상태를 새로 만들어 거기에 둡니다.
--     나중에 중고등부 명단을 받으면 이름으로 대조해서, 그 명단에도 없는 학생만 퇴소로 넘깁니다.
--     보류 학생은 화면(관찰기록·픽업체크·대시보드)에서 빠지지만 기록은 그대로 남습니다.
--
--   반 → 삭제
--     "초등부는 이 명단이 확정이라 다른 반이 있어서는 안돼". 옛 학기의 반이 남아 있으면 반 관리
--     화면과 담임 배정에서 계속 헷갈립니다. 반을 지워도 학생·관찰기록·출결은 지워지지 않습니다
--     (연결만 끊어지고, 학년 표기는 각 기록에 글자로 남아 있습니다). 그 반의 옛 시간표만 함께
--     사라지는데, 새 학기 시간표를 이미 넣었으므로 문제되지 않습니다.
--
-- 유치부는 건드리지 않습니다(요청: "유치부는 반을 보고 구별할 수 있고"). 별도 프로그램으로
-- 관리하기로 한 대상이라 부서·학년 표기가 유치부인 학생과 반은 그대로 둡니다.
--
-- 하원 셔틀은 영향을 받지 않습니다(요청: "일단은 셔틀만 지금 준 명단에 없는 애들 나오도록").
-- 하원 체크표·실시간 셔틀은 셔틀 배정표를 이름으로 읽기 때문에, 보류 학생도 그대로 나옵니다.

-- ── ① 보류 상태 추가 ────────────────────────────────────────────────────────
-- status에 '보류'를 허용합니다. 기존 제약의 이름이 환경마다 다를 수 있어(직접 붙여넣은 SQL과
-- 마이그레이션이 섞여 있었습니다) 이름을 찾지 않고 status를 다루는 검사 제약을 전부 찾아 지운 뒤
-- 새로 겁니다.
do $$
declare c record;
begin
  for c in
    select con.conname
      from pg_constraint con
      join pg_class rel on rel.oid = con.conrelid
      join pg_namespace ns on ns.oid = rel.relnamespace
     where ns.nspname = 'public'
       and rel.relname = 'wr_students'
       and con.contype = 'c'
       and pg_get_constraintdef(con.oid) ilike '%status%'
  loop
    execute format('alter table wr_students drop constraint %I', c.conname);
  end loop;
end $$;

alter table wr_students add constraint wr_students_status_check
  check (status in ('active', 'inactive', '보류'));

-- ── ② 명부에 없는 재학생 → 보류 ─────────────────────────────────────────────
-- "명부에 있는 학생"은 이번에 만든 8개 반에 속했는지로 판단합니다. 이름 대조 같은 애매한 방법을
-- 쓰지 않아 오차가 없습니다.
--
-- 무엇이 보류로 넘어갔는지 [학교 > 명부 점검]에서 이름까지 볼 수 있게 기록부터 남깁니다.
-- 조용히 처리하면 나중에 "이 학생 왜 안 보이지?"를 추적할 수 없습니다.
delete from wr_import_issues
 where source = '26-27 Primary Roster' and kind in ('명부에 없는 재학생', '보류');

insert into wr_import_issues (source, kind, student_name, detail)
select
  '26-27 Primary Roster',
  '보류',
  s.name,
  format(
    '3학기 초등부 확정 명부에 없어서 보류로 두었습니다(예전 부서: %s / 학년: %s). 화면에서는 빠지지만 기록은 그대로 있습니다. 중고등부 명단을 받으면 이름으로 대조해서, 그 명단에도 없으면 그때 퇴소로 넘깁니다. 초등부 학생인데 명부에서 누락된 경우라면 [학생 관리]에서 상태를 재학으로 되돌려주세요.',
    coalesce(s.department, '미지정'), coalesce(s.grade, '미지정')
  )
from wr_students s
where s.is_demo = false
  and s.status = 'active'
  and coalesce(s.department, '') <> '유치부'
  and coalesce(s.grade, '') !~* '유치|^K|^유'
  and (s.class_id is null or s.class_id not in (
    '3a000000-0000-4000-a000-000000000001', '3a000000-0000-4000-a000-000000000002',
    '3a000000-0000-4000-a000-000000000003', '3a000000-0000-4000-a000-000000000004',
    '3a000000-0000-4000-a000-000000000005', '3a000000-0000-4000-a000-000000000006',
    '3a000000-0000-4000-a000-000000000007', '3a000000-0000-4000-a000-000000000008'
  ));

-- 부서는 건드리지 않습니다. 중고등부일지 유치부일지 아직 확인되지 않았는데 지금 단정해두면,
-- 나중에 중고등부 명단으로 대조할 때 잘못 붙은 값이 판단을 방해합니다.
update wr_students s
   set status = '보류'
 where s.is_demo = false
   and s.status = 'active'
   and coalesce(s.department, '') <> '유치부'
   and coalesce(s.grade, '') !~* '유치|^K|^유'
   and (s.class_id is null or s.class_id not in (
     '3a000000-0000-4000-a000-000000000001', '3a000000-0000-4000-a000-000000000002',
     '3a000000-0000-4000-a000-000000000003', '3a000000-0000-4000-a000-000000000004',
     '3a000000-0000-4000-a000-000000000005', '3a000000-0000-4000-a000-000000000006',
     '3a000000-0000-4000-a000-000000000007', '3a000000-0000-4000-a000-000000000008'
   ));

-- ── ③ 명부에 없는 반 삭제 ───────────────────────────────────────────────────
-- 지우기 전에 어떤 반이 사라지는지 기록에 남깁니다.
delete from wr_import_issues where source = '26-27 Primary Roster' and kind = '삭제된 반';

insert into wr_import_issues (source, kind, student_name, detail)
select
  '26-27 Primary Roster',
  '삭제된 반',
  concat_ws(' ', c.grade, c.class_name),
  format(
    '3학기 확정 명부에 없는 반이라 삭제했습니다(담임: %s). 이 반에 속했던 학생·관찰기록·출결은 지워지지 않았고 연결만 끊어졌습니다. 필요하면 [반·담임 관리]에서 다시 만들 수 있습니다.',
    coalesce(nullif(c.teacher_name, ''), c.teacher_email, '없음')
  )
from wr_classes c
where c.is_demo = false
  and coalesce(c.department, '') <> '유치부'
  and coalesce(c.grade, '') !~* '유치|^K|^유'
  and c.id not in (
    '3a000000-0000-4000-a000-000000000001', '3a000000-0000-4000-a000-000000000002',
    '3a000000-0000-4000-a000-000000000003', '3a000000-0000-4000-a000-000000000004',
    '3a000000-0000-4000-a000-000000000005', '3a000000-0000-4000-a000-000000000006',
    '3a000000-0000-4000-a000-000000000007', '3a000000-0000-4000-a000-000000000008'
  );

-- 학생·관찰기록·출결·수강등록의 class_id는 "지우면 비우기(on delete set null)"로 연결되어 있어
-- 반을 지워도 기록 자체는 남습니다. 그 반의 옛 시간표만 함께 사라집니다.
delete from wr_classes c
where c.is_demo = false
  and coalesce(c.department, '') <> '유치부'
  and coalesce(c.grade, '') !~* '유치|^K|^유'
  and c.id not in (
    '3a000000-0000-4000-a000-000000000001', '3a000000-0000-4000-a000-000000000002',
    '3a000000-0000-4000-a000-000000000003', '3a000000-0000-4000-a000-000000000004',
    '3a000000-0000-4000-a000-000000000005', '3a000000-0000-4000-a000-000000000006',
