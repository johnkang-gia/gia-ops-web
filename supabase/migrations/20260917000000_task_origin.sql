-- 이 업무가 **어디서 온 것인가**
--
-- ── 무엇이 문제였나 ─────────────────────────────────────────────────────────
--
-- 픽업이 확정되면 업무보드에 자동으로 줄이 생깁니다. 제목이 「[픽업] 15:40 권수호 …」라
-- 사람 눈에는 구별되지만, **코드가 그것을 가리려면 제목 글자를 봐야 했습니다.**
--
-- 이 저장소에서 글자를 열쇠로 쓴 사고가 여러 번 났습니다(이름으로 학생 찾기, 이름으로
-- 반 붙이기). 제목은 사람이 고칠 수 있는 것이고, 고치는 순간 그 줄은 «픽업이 아닌 것»이
-- 됩니다 - 오류가 아니라 그냥 색이 바뀌고 단추가 사라집니다.
--
-- ── 그래서 ───────────────────────────────────────────────────────────────────
--
-- 어디서 왔는지를 **칸으로** 남깁니다. 제목을 고쳐도 픽업은 픽업입니다.

alter table public.tasks add column if not exists origin text;

comment on column public.tasks.origin is
  '이 업무를 만든 곳. ''픽업''이면 확정된 픽업에서 자동으로 생긴 줄입니다. 사람이 손으로 만든 업무는 비어 있습니다.';

-- 업무보드가 「오늘 픽업만」을 자주 셉니다.
create index if not exists tasks_origin_idx on public.tasks (origin) where origin is not null;

-- ── 이미 만들어진 픽업 업무에도 표시를 답니다 ───────────────────────────────
--
-- 지금까지 만들어진 줄은 제목으로밖에 알 수 없습니다. **한 번만** 제목을 보고 칸을
-- 채웁니다 - 앞으로는 만들 때 함께 넣으므로 이 일은 다시 하지 않습니다.
update public.tasks
   set origin = '픽업'
 where origin is null
   and title like '[픽업]%';
