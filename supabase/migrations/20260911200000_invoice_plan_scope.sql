-- 학비 청구서를 **항목별로** 나눠 발행하기
--
-- ── 무엇이 문제였나 ──────────────────────────────────────────────────
--
-- 학비 청구서 한 장에 그 학생의 학비 신청이 **전부** 실렸습니다. 정규과정과 방과후가 한
-- 줄씩 같은 종이에 들어갑니다.
--
-- 그런데 이 둘은 납기도 다르고, 그만두는 시점도 다릅니다. 방과후만 그만둔 아이에게 이미
-- 나간 청구서를 어떻게 할지가 매번 문제였고, 「방과후만 이번 달 얼마 걷혔나」를 셀 수도
-- 없었습니다 - 한 장에 섞여 있으면 그 장이 반만 결제된 상태가 되기 때문입니다.
--
-- ── 그래서 ───────────────────────────────────────────────────────────
--
-- 발행할 때 **어느 항목을 담은 청구서인지**를 함께 적습니다. 화면은 이걸로 「정규과정
-- 청구서」와 「방과후 청구서」를 갈라 셉니다.
--
-- 항목 id 가 아니라 **사람이 읽는 이름**을 굳혀 적는 이유: 요금표에서 항목 이름이 바뀌거나
-- 항목을 끄면, id 로만 가리킨 지난 청구서는 무슨 청구서였는지 설명할 수 없게 됩니다.
-- 청구서는 그때의 사실을 그대로 남기는 종이입니다.

alter table public.invoices add column if not exists plan_scope text;

comment on column public.invoices.plan_scope is
  '이 청구서가 담은 학비 항목의 이름(「정규과정」·「방과후」·「정규과정 · 방과후」). 비어 있으면 그 학생의 학비 전부를 담은 옛 청구서입니다.';

create index if not exists invoices_plan_scope_idx
  on public.invoices(plan_scope) where plan_scope is not null;
