/**
 * **「오늘은 셔틀로 보내주세요」 — 픽업의 반대 요청.**
 *
 * ── 무엇이 문제였나 ─────────────────────────────────────────────────────────
 *
 * 백서아는 수요일에 **셔틀을 안 탑니다**(하원수단: 블루웨일버스 16:30). 그래서 아침 크론이
 * 체크표에서 그 아이를 빼고 「픽업」으로 찍습니다 - 여기까지는 맞습니다.
 *
 * 그날 학부모가 보냈습니다. 「오늘 서아 셔틀로 하원부탁드립니다」
 *
 * **이건 오늘만 그 기본을 뒤집어 달라는 요청입니다.** 그런데 인박스에서 고를 수 있는 것은
 * 픽업 확정·결석·지각·특이사항뿐이라, 이 글은 「문의」로만 남고 체크표는 **여전히 픽업**
 * 이었습니다. 화면에는 오류가 아니라 **정반대의 답**이 적혀 있고, 그대로 두면 아이가
 * 셔틀을 못 탑니다. 되돌릴 수 없습니다.
 *
 * ── 왜 규칙으로 먼저 읽나 ───────────────────────────────────────────────────
 *
 * 이 문형은 뜻이 좁습니다(셔틀 + 태워/보내/하원). AI 는 실패할 수 있고 느리며, 실제로 이
 * 글을 「문의」로만 분류했습니다. 규칙이 먼저 잡고, 사람이 단추 하나로 확정합니다.
 *
 * **「안 탄다」는 반대로 읽지 않습니다.** 「오늘 셔틀 안 타요」는 픽업 쪽 이야기라, 여기서
 * 걸리면 정반대로 처리됩니다 - 이 파일이 고치려는 사고를 그대로 한 번 더 내는 셈입니다.
 *
 * 순수 함수입니다 - 화면 없이 시험할 수 있습니다.
 */

export type ShuttleRequestRead = {
  /** 셔틀에 태워달라는 요청으로 읽히는가. */
  yes: boolean;
  /** 왜 그렇게 읽었는지. 틀렸을 때 사람이 근거를 봐야 고칠 수 있습니다. */
  why: string;
};

/** 셔틀을 가리키는 말. 「차」만으로는 부족합니다 - 학원차·자가용도 차입니다. */
const SHUTTLE = /(셔틀|shuttle|스쿨버스|학교\s*버스)/i;

/** 태워달라는 쪽. */
const ASK_ON = /(타고|태워|태우|타요|탈게|탑승|이용|보내|하원\s*부탁|하원\s*해|하원\s*시켜|하원\s*으로|로\s*하원|으로\s*하원)/;

/** 안 탄다는 쪽. 여기 걸리면 **요청이 아닙니다.** */
const ASK_OFF = /(안\s*타|못\s*타|안\s*탑|타지\s*않|제외|빼\s*주|취소|말고)/;

export function readsShuttleRequest(text: string): ShuttleRequestRead {
  const t = (text ?? "").replace(/\s+/g, " ").trim();
  if (!t) return { yes: false, why: "본문이 없습니다" };
  if (!SHUTTLE.test(t)) return { yes: false, why: "셔틀 이야기가 아닙니다" };

  // **부정이 먼저입니다.** 「셔틀 안 타고 제가 데리러 갑니다」는 픽업입니다.
  if (ASK_OFF.test(t)) return { yes: false, why: "셔틀을 안 탄다는 쪽으로 읽힙니다" };
  if (!ASK_ON.test(t)) return { yes: false, why: "셔틀을 말하지만 태워달라는 말이 없습니다" };

  return { yes: true, why: "오늘 셔틀로 보내달라는 요청으로 읽힙니다" };
}
