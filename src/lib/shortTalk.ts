/**
 * **「감사합니다」 같은 짧은 인사말을 가려냅니다.**
 *
 * ── 왜 필요한가 ──────────────────────────────────────────────────────
 *
 * 토들로 들어오는 글의 상당수가 「감사합니다」·「네~」·「알겠습니다」입니다. 지금은 이런
 * 글도 전부 AI에게 물어봅니다. 두 가지가 낭비입니다.
 *
 *   · 돈 - 한 건마다 AI 호출이 나갑니다. 하루 수십 건이면 그만큼 쌓입니다.
 *   · 사람 - 인박스에 줄이 늘어납니다. 볼 것이 아닌 줄이 섞이면 목록 전체를 안 보게 됩니다.
 *
 * ── 무엇을 조심하나 ──────────────────────────────────────────────────
 *
 * **짧다고 안 중요한 것이 아닙니다.** 「오늘 결석」은 다섯 글자고, 「3시 픽업」은 네 글자이며,
 * 둘 다 놓치면 아이가 잘못된 곳으로 갑니다. 그래서 길이만으로는 절대 거르지 않습니다.
 *
 * 두 관문을 **모두** 지나야 인사말로 봅니다.
 *
 *   ① 뜻이 실린 낱말이 하나도 없어야 합니다(결석·픽업·시각·날짜·숫자 …).
 *   ② 알고 있는 인사말 꼴이어야 합니다. 모르는 말은 인사말이 아니라 **모르는 말**입니다.
 *
 * 애매하면 거르지 않습니다. 잘못 거른 한 건은 아무 흔적 없이 사라지지만, 안 거른 한 건은
 * 사람이 목록에서 한 번 보고 넘기면 그만입니다. 두 실수의 무게가 다릅니다.
 */

/**
 * 이 낱말이 하나라도 있으면 **절대 안 거릅니다.**
 *
 * 넓게 잡습니다 - 여기 걸려서 AI를 한 번 더 부르는 것은 돈만 조금 더 드는 일이고,
 * 여기서 새어 나가면 아이가 관련된 연락을 놓칩니다.
 */
const MEANINGFUL =
  /[0-9]|결석|지각|조퇴|아파|아프|아픔|병원|열이|열나|기침|콧물|장염|독감|코로나|픽업|데리러|데려|하원|등원|셔틀|버스|차량|타|안\s*가|못\s*가|늦|약|투약|체험|현장|상담|문의|질문|부탁|알려|확인\s*부탁|시간|시|분|오늘|내일|모레|어제|이번\s*주|다음\s*주|요일|월요|화요|수요|목요|금요|absent|sick|pick\s*up|late|early|fever|hospital|medicine|tomorrow|today/i;

/**
 * 알고 있는 인사말 꼴.
 *
 * 목록을 짧게 둡니다. 길어질수록 「이것도 인사말이겠지」로 새는 말이 늘어나는데, 그렇게
 * 새 나간 글은 **아무 데도 안 남습니다**.
 */
const PLEASANTRY =
  /^(?:네|넵|넹|예|응|감사합니다|감사해요|감사드립니다|감사|고맙습니다|고마워요|고마워|알겠습니다|알겠어요|알겠습니당|알겠|확인했습니다|확인했어요|확인|넵확인|좋은하루되세요|좋은하루|수고하세요|수고하셨습니다|수고많으셨습니다|고생하셨습니다|안녕하세요|안녕히계세요|안녕히가세요|잘부탁드립니다|ㅎ+|ㅋ+|ㅠ+|ㅜ+|thankyou|thanks|thx|ok|okay|okey|gotit|noted|sure|yes|yep|greatthanks|nice|good|welcome|hi|hello)+$/i;

/**
 * 글자만 남깁니다 - 띄어쓰기·문장부호·이모지·자모 반복을 걷어냅니다.
 *
 * 「감사합니다~^^」·「네!!」·「👍」가 모두 같은 것으로 보여야 합니다.
 */
export function flatten(text: string): string {
  return String(text ?? "")
    // 이모지·기호를 통째로 걷어냅니다. 한글·영문·숫자만 남깁니다.
    .replace(/[^\p{L}\p{N}]/gu, "")
    .toLowerCase()
    .trim();
}

/** 이모지·문장부호밖에 없는 글인가(👍, ^^, !!). */
export function isSymbolOnly(text: string): boolean {
  return String(text ?? "").trim().length > 0 && flatten(text).length === 0;
}

/**
 * 넘겨도 되는 짧은 인사말인가.
 *
 * 뜻이 실린 낱말이 하나라도 있으면 **무조건 false** 입니다 - 「네 오늘 결석입니다」는
 * 「네」로 시작하지만 인사말이 아닙니다.
 */
export function isPleasantry(text: string): boolean {
  const raw = String(text ?? "").trim();
  if (!raw) return false;

  // 기호·이모지뿐인 글(👍, ^^). 읽을 것이 없습니다.
  if (isSymbolOnly(raw)) return true;

  // 뜻이 실린 낱말이 있으면 길이와 상관없이 사람이 봅니다.
  if (MEANINGFUL.test(raw)) return false;

  const flat = flatten(raw);
  // 긴 글은 인사말이라도 사연이 붙어 있을 수 있습니다. 짧은 것만 봅니다.
  if (flat.length > 20) return false;

  return PLEASANTRY.test(flat);
}

/** 인박스에 남길 한 줄. 무엇을 왜 넘겼는지 나중에 확인할 수 있어야 합니다. */
export function pleasantryNote(text: string): string {
  const raw = String(text ?? "").trim().slice(0, 40);
  return `짧은 인사말이라 AI를 부르지 않고 넘겼습니다: "${raw}"`;
}
