-- ===== 「이 칸 다 찍었습니다」 =====
--
-- 요청: "애들이 계속 자리를 옮겨놔서 책장 정리하는 거 한꺼번에는 어려울 것 같고, 등급별로
-- 책장 등록이 완료되면(즉 2-1부터 2-5까지 2등급 책장 등록이 완료되면) 그 등급 정리를 시작할
-- 수 있도록 만들어줘."
--
-- ── 왜 칸마다 '끝' 표시가 필요한가 ────────────────────────────────────────
-- 지금은 칸에 몇 권 세어졌는지만 압니다. 그런데 **'68권 세어졌다'와 '다 세었다'는 다른
-- 말입니다.** 중간에 멈춘 칸도 68권일 수 있습니다. 자료만 봐서는 구분할 방법이 없습니다.
--
-- 그 칸을 다 비워 봤는지는 **사람만 압니다.** 그래서 사람이 누르는 표시를 하나 둡니다.
-- 이 표시가 있어야 "2등급 칸 다섯 개가 전부 끝났으니 이제 2등급을 정리해도 된다"고 말할 수
-- 있습니다. 끝나지도 않은 칸을 바탕으로 정리 계획을 세우면, 아직 안 꺼낸 책들이 계획에서
-- 통째로 빠진 채 책장을 다시 짜게 됩니다.
--
-- ── 한 번 누르면 끝이 아닙니다 ────────────────────────────────────────────
-- 아이들이 책을 옮겨 놓으면 끝난 칸도 다시 어긋납니다. 그래서 '언제' 끝냈는지를 시각으로
-- 담습니다. 그 뒤에 그 칸에서 또 찍힌 책이 있으면(lib_shelf_check.checked_at 이 더 나중이면)
-- 화면이 "다시 봐야 합니다"라고 말할 수 있습니다. 참/거짓 한 칸으로는 그 말을 못 합니다.

alter table public.lib_locations
  add column if not exists checked_done_at timestamptz,
  add column if not exists checked_done_by text;

comment on column public.lib_locations.checked_done_at is
  '이 칸을 다 비워 찍었다고 사람이 표시한 시각. 비어 있으면 아직 하는 중입니다. 그 뒤에 새로 찍힌 책이 있으면 다시 봐야 한다는 뜻입니다.';

notify pgrst, 'reload schema';
