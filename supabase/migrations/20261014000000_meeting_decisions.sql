-- 회의에서 정한 것을 적을 자리가 없었습니다
-- ═══════════════════════════════════════════════════════════════════════
--
-- 학사 행사는 「모여서 정하고, 한 주씩 나눠 맡고, 다시 모여 본다」로 굴러갑니다. 그런데
-- 회의 줄에는 날짜와 제목만 있어서 **무엇을 정했는지**는 어디에도 안 남았습니다. 그러면
-- 다음 회의에서 지난번에 정한 것을 다시 이야기하게 되고, 그 자리에 없었던 사람은 결정을
-- 물어볼 데가 없습니다.
--
-- `note` 는 회의 **전에** 적어두는 메모 자리라 그대로 둡니다. 정한 것은 성격이 다릅니다 -
-- 메모는 바뀌어도 되지만 결정은 근거로 쓰입니다. 한 칸에 섞으면 나중에 어느 쪽이 결정이었는지
-- 아무도 못 가릅니다.
alter table public.academic_checklist_meetings
  add column if not exists decisions text;

comment on column public.academic_checklist_meetings.decisions is
  '그 회의에서 정한 것. 회의 전 메모(note)와 섞지 않습니다 - 메모는 바뀌어도 되지만 결정은 근거가 됩니다.';
