import pkg from "../../package.json";

// 사이드바 아래에 뜨는 현재 버전.
//
// **손으로 적던 것을 package.json에서 읽어오도록 바꿨습니다.**
//
// 예전에는 여기에 "0.345.0"처럼 문자열을 박아두고 "버전 올릴 때 같이 고치기"로 두었는데,
// 실제로는 그 뒤로 다섯 번 배포하는 동안 한 번도 안 고쳐졌습니다. 그래서 화면에는 계속
// v0.345.0이 떠 있었고, 담당자가 "이게 반영된 건가?"를 확인할 방법이 사라졌습니다.
// 두 곳에 같은 값을 적어두고 사람이 맞추기로 하면 언젠가 반드시 어긋납니다.
//
// `import`는 **빌드할 때** 값이 코드 안으로 들어가므로, 예전 주석이 걱정하던 "런타임에
// package.json 파일을 못 찾는" 문제(Vercel 파일 트레이싱)와는 상관이 없습니다.
// fs로 읽는 것이 아니라 번들에 박히는 것입니다.
export const APP_VERSION: string = pkg.version;
