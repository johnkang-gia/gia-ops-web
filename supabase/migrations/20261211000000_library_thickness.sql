/*
  ── 책 두께와 칸 폭 ─────────────────────────────────────────────────────────

  "책의 크기를 가늠할 수 있는 정보가 없을까? 그 정보를 통해서 두께를 설정(얇은 책 2권과 일반
  책 1권은 거의 비슷한 두께)해서 책장에 넣을 수 있도록 ... 문제는 각 책의 두께가 전부 다르다는
  거야."

  권수로 칸을 채우면 틀립니다. 80쪽짜리 그림책 30권과 400쪽짜리 소설 30권은 꽂는 데 드는
  자리가 두 배 넘게 다릅니다. 그래서 칸을 **권수가 아니라 폭(mm)** 으로 채울 수 있게 두 칸을
  만듭니다.

  ── 두께를 어디서 아는가 ───────────────────────────────────────────────────
  조회처에 실제 치수(physical_dimensions)를 물어봤습니다. 표본 20권 중 **0권**이 치수를 갖고
  있었습니다(쪽수는 14권, 판형은 5권). 치수는 사실상 없는 자료입니다.

  대신 쪽수가 있습니다. 종이 한 장이 두 쪽이고, 책 종이 한 장은 0.10~0.15mm 입니다. 그래서
    두께(mm) ≈ (쪽수 ÷ 2) × 종이 두께 + 표지
  로 가늠할 수 있습니다. 320쪽 무선제본이면 160장 × 0.12 + 1.5 ≈ 20mm - 실제와 비슷합니다.

  종이 두께는 책마다 다르니 이 가늠에는 늘 오차가 있습니다. 그 오차를 줄이는 방법이 하나
  있습니다 - **지금 꽂혀 있는 책장 자체가 자(ruler)입니다.** 꽉 찬 칸의 책 두께를 모두 더하면
  그 값이 그 칸의 폭이어야 합니다. 어긋나는 만큼이 종이 두께를 잘못 잡은 양이고, 한 번 재어
  적어 둔 칸 폭(capacity_mm)이 있으면 그 비율로 전체를 바로잡을 수 있습니다.

  thickness_mm 은 **아는 경우에만** 채웁니다(조회처가 치수를 주거나 사람이 재었을 때).
  비어 있으면 화면이 쪽수로 가늠합니다 - 가늠한 값을 저장해 두면 나중에 그것이 사실인 척하게
  되니까요.
*/

alter table public.lib_books
  add column if not exists thickness_mm numeric;

comment on column public.lib_books.thickness_mm is
  '책등 두께(mm). 조회처가 치수를 주거나 사람이 재어 적은 값만 들어갑니다. 비어 있으면 쪽수로 가늠합니다(가늠값은 저장하지 않습니다).';

alter table public.lib_locations
  add column if not exists capacity_mm integer;

comment on column public.lib_locations.capacity_mm is
  '칸의 가로 폭(mm). 적어 두면 계획이 권수가 아니라 폭으로 칸을 채웁니다. 비어 있으면 지금 그 칸에 꽂힌 책들의 두께 합으로 가늠합니다.';

notify pgrst, 'reload schema';
