-- (1) 노선: 있으면 갱신, 없으면 추가. **id는 유지**합니다 - 기사님 설정링크와 GPS 기기가
--     노선 id로 연결돼 있어서, 지우고 새로 만들면 그 연결이 전부 끊어집니다.
insert into shuttle_routes (direction, route_no, name, driver_name, driver_phone, teacher_name, teacher_phone, depart_time, sort_order, active, term)
select '하원', r.route_no, nullif(r.name,''), nullif(r.driver,''), nullif(r.dphone,''),
       nullif(r.teacher,''), nullif(r.tphone,''), r.dep::time, r.ord, true, '정규학기'
  from _r r
 where not exists (select 1 from shuttle_routes x
                    where x.direction='하원' and x.term='정규학기' and x.route_no=r.route_no);

update shuttle_routes x
   set name=nullif(r.name,''), driver_name=nullif(r.driver,''), driver_phone=nullif(r.dphone,''),
       teacher_name=nullif(r.teacher,''), teacher_phone=nullif(r.tphone,''),
       depart_time=r.dep::time, sort_order=r.ord, active=true
  from _r r
 where x.direction='하원' and x.term='정규학기' and x.route_no=r.route_no;

-- 엑셀에 없는 하원 노선은 쉬게만 합니다(지우지 않습니다 - 지난 기록이 딸려 사라지면 안 됩니다).
update shuttle_routes x set active=false
 where x.direction='하원' and x.term='정규학기'
   and not exists (select 1 from _r r where r.route_no=x.route_no);

-- (2) 정류장·배정은 통째로 다시 만듭니다(엑셀이 기준이므로).
delete from shuttle_assignments a
 using shuttle_stops s, shuttle_routes r
 where a.stop_id=s.id and s.route_id=r.id and r.direction='하원' and r.term='정규학기';
delete from shuttle_stops s
 using shuttle_routes r
 where s.route_id=r.id and r.direction='하원' and r.term='정규학기';

insert into shuttle_stops (route_id, seq, stop_time, address)
select r.id, s.seq, nullif(s.stop_time,''), s.address
  from _s s join shuttle_routes r
    on r.direction='하원' and r.term='정규학기' and r.route_no=s.route_no;

-- (3) 배정 + 명부 연결(그 이름이 명부에 딱 한 명일 때만).
insert into shuttle_assignments (stop_id, student_name_raw, class_raw, weekdays, guardian_phone, student_id, unlinked_reason)
select st.id, a.student, nullif(a.class_raw,''), a.weekdays, nullif(a.phone,''),
       u.student_id,
       case when u.student_id is not null then null
            when public.shuttle_class_department(a.class_raw) = '유치부' then '유치부'
            else '퇴소' end
  from _a a
  join shuttle_routes r on r.direction='하원' and r.term='정규학기' and r.route_no=a.route_no
  join shuttle_stops  st on st.route_id=r.id and st.seq=a.seq
  left join (
    select key, min(id::text)::uuid as student_id from (
      select public.norm_name(name) as key, id from wr_students where status='active' and is_demo=false
      union all
      select public.norm_name(name_en), id from wr_students where status='active' and is_demo=false and coalesce(name_en,'')<>''
      union all
      select public.norm_name(pattern), student_id from attendance_learning_rules where kind='alias' and student_id is not null
    ) z group by key having count(distinct id)=1
  ) u on u.key = public.norm_name(a.student);

commit;

select coalesce(a.unlinked_reason,'명부연결') as "상태", count(*) as "건수"
  from shuttle_assignments a
  join shuttle_stops s on s.id=a.stop_id
  join shuttle_routes r on r.id=s.route_id and r.direction='하원'
 group by 1 order by 2 desc;
