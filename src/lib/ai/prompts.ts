export function buildMeetingEntryBlock(
  entry: { date: string; attendees: string; content: string },
  label?: string
): string {
  return (
    `[${label || "회의 정보"}]\n날짜: ${entry.date}\n참석자: ${entry.attendees}` +
    `\n\n[회의 내용(원문 - 메모/구어체일 수 있음, 그대로 베끼지 말고 정리할 것)]\n${entry.content}`
  );
}
