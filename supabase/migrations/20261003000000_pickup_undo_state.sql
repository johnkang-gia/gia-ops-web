-- **「아님」을 잘못 눌렀을 때 되돌릴 수 있게 합니다.**
--
-- 인박스·문의함에서 ✕(「이 연락은 그게 아닙니다」)를 누르면 연락이 「무시」가 되고 종류가
-- 「문의」로 바뀝니다. 그런데 **누르기 전 상태를 아무 데도 안 남겼습니다.** 그래서 잘못
-- 눌러도 원래대로 되돌릴 방법이 없었고, 잘못 내린 결석 연락은 그대로 묻혔습니다.
--
-- 되돌릴 수 없는 단추는 사람을 조심스럽게 만드는 것이 아니라, **안 누르게** 만듭니다.
-- 그러면 틀린 자동 판정이 그대로 남습니다.
--
-- 되돌리기용 스냅샷을 칸으로 둡니다. 되돌린 뒤에는 비웁니다 - 남겨 두면 「되돌릴 수 있는
-- 것」과 「이미 되돌린 것」이 화면에서 똑같이 보입니다.
alter table public.pickup_requests
  add column if not exists undo_state jsonb;

comment on column public.pickup_requests.undo_state is
  '「아님」을 누르기 직전의 상태({status, kind, ai_is_pickup, at, by}). 되돌리면 비웁니다.';
