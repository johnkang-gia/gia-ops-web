-- ===== 인보이스에 '어느 분류인가'를 남깁니다 =====
--
-- 지금까지 인보이스는 학생당 한 장이었고, 그 학생에게 붙은 항목을 전부 담았습니다.
-- 그런데 실제 청구는 그렇게 나가지 않습니다 - 교재비는 교재비대로, 교복은 교복대로
-- 따로 청구합니다(올톡페이에 올라간 지난 청구 자료가 그렇게 되어 있습니다). 시기도
-- 다릅니다. 교재는 학기 시작 전에, 교복은 치수를 잰 뒤에 나갑니다.
--
-- 한 장으로 묶으면 교복 치수가 안 끝난 아이 때문에 교재비 청구까지 못 나갑니다.
--
-- 그래서 인보이스에 분류를 답니다.
--   · null      = 통합 - 그 학생의 모든 항목을 한 장에 담은 인보이스(지금까지의 방식)
--   · '교재' 등 = 그 분류만 담은 인보이스
--
-- 이미 발행된 것은 전부 통합이므로 null 로 둡니다. 나중에 화면에서 "이 학생 교재비는
-- 나갔나"를 물으려면 이 칸이 있어야 합니다. 총액만 보고는 알 수 없습니다.

alter table public.invoices add column if not exists category text;

comment on column public.invoices.category is
  '이 인보이스가 담은 항목 분류. null 이면 분류를 가리지 않고 전부 담은 통합 인보이스입니다.';

-- 같은 학기·같은 학생·같은 분류로 두 번 발행되는 것을 막지는 않습니다. 되돌리기(취소) 없이
-- 다시 발행해야 하는 경우가 실제로 있어서(금액 정정) 막으면 일이 멈춥니다. 대신 화면에서
-- "이미 발행됨 - 한 장 더 나갑니다" 로 경고합니다.
create index if not exists invoices_student_category_idx
  on public.invoices (student_id, category);
