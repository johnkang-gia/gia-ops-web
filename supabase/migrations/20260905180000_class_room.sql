-- ===== 반의 교실 위치 =====
--
-- 셔틀을 타지 않는 아이를 보호자가 데리러 올 때, 행정실은 "그 아이가 지금 어디 있는가"를
-- 답해야 합니다. 지금은 반 이름(G4A)만 있고 그 반이 몇 층 어느 교실인지는 **사람 머릿속에만**
-- 있습니다. 새로 온 직원이나 대체 인력은 답을 못 합니다.
--
-- 시간표에 강의실을 적는 칸을 따로 두지 않은 이유는, 하원 시각에는 아이가 담임반 교실에
-- 모여 있기 때문입니다. 그 한 곳만 알면 됩니다.

alter table public.wr_classes
  add column if not exists room text;

comment on column public.wr_classes.room is
  '교실 위치(예: 3층 302호). 하원 픽업 때 보호자를 어디로 안내할지에 씁니다. 비어 있으면 화면에는 반 이름만 나옵니다.';
