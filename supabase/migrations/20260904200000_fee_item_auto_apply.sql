-- ===== 학비외 항목: 대상과 '자동으로 붙느냐' 를 나눕니다 =====
--
-- 지금은 학년을 고르면 **그 학년 전원에게 자동으로 붙습니다.** 그래서 두 가지가 한 칸에
-- 섞여 있었습니다.
--
--   ① 공통 교과서  — 3학년이면 전원이 삽니다
--   ② 3학년 중국어 — 3학년 것이 맞지만, 3학년 중에도 하는 아이와 안 하는 아이가 있습니다
--
-- ②를 표현할 방법이 없어서 지금은 둘 중 하나를 하게 됩니다.
--   · 3학년을 골라 전원에게 붙인 뒤, 안 하는 아이를 하나씩 뺀다 (뺄 것을 잊으면 청구됩니다)
--   · 대상을 비워두고 하는 아이를 하나씩 넣는다 (그러면 이 항목이 3학년 것이라는 사실이
--     어디에도 안 남아, 인보이스 표에서 걸러낼 수가 없습니다)
--
-- 앞의 방식은 **틀리면 돈이 잘못 청구되고**, 뒤의 방식은 표가 다시 가로로 길어집니다.
--
-- 그래서 칸을 하나 더 둡니다. 대상(학년·반)은 **누구를 위한 것인가**만 뜻하고,
-- 자동으로 붙일지는 이 칸이 따로 정합니다.
--
--   auto_apply = true   대상 전원에게 자동으로 (공통 교과서)
--   auto_apply = false  대상에서 **고른 아이에게만** (3학년 중국어)
--
-- false 여도 대상은 그대로 뜻이 있습니다 - 인보이스 표에서 3학년 명단에만 열이 서고,
-- 2학년 표에는 안 뜹니다. 그것이 애초에 대상을 적는 이유입니다.

alter table public.fee_items
  -- 지금까지 만든 항목은 전부 '전원 자동' 이었습니다. 기본값을 true 로 두어야 지금 붙어
  -- 있는 것이 그대로 유지됩니다. 여기서 false 로 뒤집으면 이미 청구한 아이들의 항목이
  -- 한꺼번에 사라집니다.
  add column if not exists auto_apply boolean not null default true;

comment on column public.fee_items.auto_apply is
  'true=대상 전원에게 자동(공통 교과서) / false=대상 중에서 고른 아이에게만(선택 과목 교재). false여도 대상(학년·반)은 인보이스 표에서 열을 세울지 정하는 데 쓰입니다.';

-- 고른 아이만 사는 항목은 student_fee_items 를 훨씬 자주 읽습니다(기본이 없으니 전부
-- 개별 기록입니다). 항목 기준으로 찾는 자리에 색인을 둡니다.
create index if not exists student_fee_items_item_idx on public.student_fee_items (item_id);
