/**
 * **로그인 없이 여는 화면의 짧은 주소 코드** — 만드는 곳은 한 곳입니다.
 *
 * ── 이 코드가 지키는 것 ─────────────────────────────────────────────────────
 *
 * `/b/{코드}` · `/d/{코드}` 는 **로그인을 지나갑니다.** 주소를 아는 사람은 누구나 안내보드와
 * 운영 대시보드를 그대로 봅니다 - 그 화면에는 오늘 하원 명단, 학생 이름, 시간표, 들어온
 * 연락이 다 떠 있습니다. 즉 이 짧은 글자가 사실상 열쇠입니다.
 *
 * ── 무엇이 문제였나 ─────────────────────────────────────────────────────────
 *
 * 두 화면이 각자 같은 함수를 손으로 적어 두었고, 둘 다 이랬습니다.
 *
 *   · **글자 4개** — 쓰는 글자가 31개라 31⁴ ≈ 92만 가지입니다. 사람이 외우기엔 좋지만,
 *     기계가 92만 개를 한 번씩 눌러보는 데는 오래 걸리지 않습니다.
 *   · **`Math.random()`** — 보기에만 무작위이고 비밀용이 아닙니다. 같은 브라우저에서 만든
 *     코드 몇 개를 알면 다음 코드를 좁힐 수 있습니다.
 *
 * 둘 다 「안 뚫렸다」가 아니라 **「뚫려도 아무 데도 안 남는다」**는 종류의 문제입니다.
 * 주소로 들어온 사람은 로그인을 안 했으니 기록에 이름이 없습니다.
 *
 * ── 그래서 ──────────────────────────────────────────────────────────────────
 *
 *   · **글자 8개** — 31⁸ ≈ 8,500억 가지. 눌러보는 방법이 현실적으로 막힙니다.
 *   · **`crypto.getRandomValues`** — 비밀값에 쓰라고 만든 난수입니다. 브라우저·서버 모두
 *     있습니다.
 *   · **나머지 연산을 쓰지 않습니다.** 256 을 31 로 나누면 딱 안 떨어져서, 그냥 `% 31` 을
 *     하면 앞쪽 글자가 조금 더 자주 나옵니다. 남는 구간의 값은 버리고 다시 뽑습니다.
 *
 * 눈으로 보고 손으로 옮겨 치는 값이라 헷갈리는 글자(0/O, 1/I/l)는 그대로 뺍니다 - 가장 흔한
 * 실수가 0과 O 입니다. 길어진 만큼 타이핑이 늘지만, 이 주소는 **한 번 쳐서 띄워두는** 화면
 * (로비 TV·사무실 모니터)에 씁니다. 매일 치는 값이 아닙니다.
 */

const SHORT_CODE_CHARS = "23456789abcdefghjkmnpqrstuvwxyz"; // 31자
const LIMIT = 256 - (256 % SHORT_CODE_CHARS.length); // 248 — 여기 이상은 버립니다

export function randomShortCode(len = 8): string {
  let out = "";
  const buf = new Uint8Array(len * 2); // 버리는 값을 감안해 넉넉히 뽑습니다
  while (out.length < len) {
    crypto.getRandomValues(buf);
    for (const b of buf) {
      if (b >= LIMIT) continue; // 치우침을 만드는 구간은 버립니다
      out += SHORT_CODE_CHARS[b % SHORT_CODE_CHARS.length];
      if (out.length === len) break;
    }
  }
  return out;
}
