-- 학생 명부 엑셀(26-27 GIA [Teacher V]) 대조 결과 반영
--
-- ── 무엇을 대조했나 ─────────────────────────────────────────────────────────
--
-- 담임 선생님 칸으로 반을 정해 103명을 맞댔습니다. 반 글자만 믿으면 안 됩니다 - 명부에
-- `G3J` 는 Ms. June, `G3` 는 Ms. Janelle 이고 `G4` 는 두 반이 같은 글자를 씁니다.
--
-- 이름·생년월일·영문명·학년은 103명 전원 일치했습니다. 아래 두 가지만 달랐습니다.
--
-- ── 짚는 방법 ───────────────────────────────────────────────────────────────
--
-- **학생 번호(id)로 짚습니다.** 이름으로 고르면 김재이 셋이 함께 걸립니다. 번호는 위
-- 대조에서 «이름 + 반» 으로 한 명씩 확인해 뽑은 것입니다.

-- ── ① 반 정정 ──────────────────────────────────────────────────────────────
--
-- 마리아 파즈 마누키안 — 명부는 G4R(Ms. Rachel), 앱은 G4S(Ms. Song) 이었습니다.
-- 명부가 맞는 것으로 확인됐습니다.
--
-- **이름 칸과 연결 칸을 함께 바꿉니다.** 한쪽만 바꾸면 화면에는 반 이름이 잘 보이는데
-- 배정·시간표·담임 판정은 예전 반을 따릅니다(CLAUDE.md 2-5).
update public.wr_students
   set class_name = 'G4R',
       class_id   = '3a000000-0000-4000-a000-000000000006'
 where id = '776a466b-6b9d-442b-a9bd-12398377d73b';

-- ── ② 방과후 등록 누락 6명 ─────────────────────────────────────────────────
--
-- 명부의 After School 칸이 `E`(매일)인데 앱에는 등록이 없던 학생들입니다. 등록이 없으면
-- 그 학생은 학비 청구에서 조용히 빠집니다 - 화면에 오류로 안 보이고 «청구할 것이 없는
-- 학생»으로 보입니다.
--
--   김준영(G2J) · 심규민(G2J) · 황라원(G2J) · 김나율(G2J) · 조하윤(G2A) · 권수호(G4S)
--
-- 납부 옵션은 **「월 납부」**(할인 0%)입니다. 이미 등록된 5일반 74명 중 70명이 이 옵션을
-- 쓰고 있어 기본값으로 삼았습니다. 실제로 다른 옵션을 고르신 가정이 있으면 화면에서
-- 바꿔주셔야 합니다 - 옵션에 따라 금액이 달라집니다(5개월 5% · 10개월 10% 할인).
insert into public.student_fee_enrollments (student_id, plan_id, option_id, term_id, active, note)
select v.student_id::uuid,
       '1ed0c344-e2e2-4e27-8be8-837c57a70efc'::uuid,   -- 방과후 5일반
       'aa1d751d-e8cd-4d94-85d1-da4ebe38ba3a'::uuid,   -- 월 납부
       '3a000000-0000-4000-9000-000000000003'::uuid,
       true,
       '명부(26-27 Teacher V) 대조로 추가 — After School: E'
  from (values
    ('963bd3cb-1457-4c6c-9087-6d5af81a44e0'),  -- 김준영 G2J
    ('8c0a3680-b0cb-c340-3cf0-0d6ce89aa67a'),  -- 심규민 G2J
    ('4f9e8881-0538-38ee-bd60-f6cfd51ad585'),  -- 황라원 G2J
    ('e6b5fb67-de6c-f1af-c04b-9b65f06f2f75'),  -- 김나율 G2J
    ('06cb685b-31b8-41d2-bfed-bb65ef1a150a'),  -- 조하윤 G2A
    ('ce18385f-9a5e-566d-bc68-702581dae771')   -- 권수호 G4S
  ) as v(student_id)
 -- 두 번 돌아도 두 줄이 생기지 않게 합니다. 마이그레이션은 다시 돌 수 있어야 합니다.
 where not exists (
   select 1 from public.student_fee_enrollments e
    where e.student_id = v.student_id::uuid
      and e.plan_id = '1ed0c344-e2e2-4e27-8be8-837c57a70efc'::uuid
      and e.active
 );

