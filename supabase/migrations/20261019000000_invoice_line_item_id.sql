-- 청구서 줄에 **어느 항목이었는지** 번호를 남깁니다.
--
-- ── 무엇이 문제였나 ──────────────────────────────────────────────────
--
-- 줄에는 이름만 있었습니다(`invoice_lines.name`). 그런데 이름이 같은 항목이 넷 있습니다 —
-- 「《加油(Go for it)-小学中文 3》」가 2·3·4·5학년용으로 각각 있고, 갈리는 것은 한글 이름
-- (`name_ko`)뿐입니다.
--
-- 그래서 「이 항목이 이미 나갔는가」를 이름으로 세면 **2학년 것 하나가 나갔을 때 넷이 모두
-- 나간 것으로 읽힙니다.** 아직 안 나간 4학년 교재가 화면에 「받음」으로 뜨고 발행에서도
-- 빠집니다 - 받아야 할 돈이 조용히 사라지는 쪽입니다. 오류가 아니라 「이미 받은 것」으로
-- 보이므로 아무도 못 찾습니다.
--
-- ── 그래서 ───────────────────────────────────────────────────────────
--
-- 번호를 함께 적습니다. 번호는 겹치지 않습니다(CLAUDE.md §2-4-1 과 같은 이유).
--
-- **이름은 그대로 둡니다.** 청구서에 찍히는 글자는 이름이고, 항목을 나중에 지워도 그때 나간
-- 종이는 안 바뀌어야 합니다. 번호는 판정에만 씁니다.
--
-- 옛 줄은 번호가 빕니다. 그 줄은 이름으로 볼 수밖에 없는데, 이름이 겹치면 **잠그지 않고
-- 사람에게 묻습니다** - 모르는 채로 잠그면 받을 돈이 사라지고, 모르는 채로 열면 두 번
-- 청구됩니다. 둘 다 나쁘므로 화면이 그 사실을 적습니다.

alter table public.invoice_lines
  add column if not exists item_id uuid references public.fee_items(id) on delete set null;

comment on column public.invoice_lines.item_id is
  '어느 학비외 항목이었나. 이름이 같은 항목이 넷 있어서(학년별 중국어 교재) 이름으로는 못 가릅니다. 판정에만 쓰고, 청구서에 찍히는 글자는 name 입니다.';

-- 「이 항목이 이미 나갔는가」가 주 질의입니다.
create index if not exists invoice_lines_item_idx
  on public.invoice_lines (item_id)
  where item_id is not null;
